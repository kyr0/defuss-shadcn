import { fenceFlags } from '../../src/documentation/lib/mdx-example.ts';
import { STANDALONE_APPS, STANDALONE_DECKS, STANDALONE_DOCS, appName, pageRel, pageSourceRel, standaloneAppId, standaloneDeckId, standaloneDocId, standaloneSource } from '../../src/documentation/lib/page-dirs.ts';
/**
 * Why: src/documentation/ is a defuss-ssg project - the doc pages are authored
 * as MDX (pages/) with TSX components (lib/) and client runtime TS (runtime/),
 * while public/ is copied to the output root verbatim by the SSG build. None
 * of these authoring subtrees may be copied 1:1 into dist/ by build.ts or
 * flagged by verify's `dist 1:1` gate - this is the shared exclusion list.
 *
 * Mapping into dist/documentation/:
 *   pages/{name}.mdx        → {name}.html        (defuss-ssg renders)
 *   public/{path}           → {path}             (defuss-ssg copies)
 *   runtime/{name}.ts       → js/{name}.js       (tsc pre-step in build-docs)
 *   lib/, data/, config.ts  → (build-time only, never shipped)
 *   tsconfig.json           → (editor-only JSX types for .tsx, never shipped)
 */
/**
 * The standalone pages (a deck rendered chrome-free as deck-<slug>.html so the
 * Getting Started rail can frame it; a scaffold as app-<name>.html on its own
 * bundle; a document as full-<slug>.html on the whole system) are listed by
 * the docs lib's layout owner, src/documentation/lib/page-dirs.ts - the
 * producer (build-docs.ts), the docs components that link them and verify all
 * read the same list. Each file sits beside its source page, in the page's
 * section folder: the *File functions give the docs-root-relative path.
 * VERIFIED: (paper-fullscreen.e2e) the full-screen document scrolls, its
 * diagram, charts, BibTeX and icons initialize on all.js, and it follows the
 * OS color scheme.
 */
export { STANDALONE_APPS, STANDALONE_DECKS, STANDALONE_DOCS, appName };

/** The generated full-screen page of a scaffold page slug, from the docs root (`application/app-notes.html`). */
export const standaloneAppFile = (slug: string): string => pageRel(standaloneAppId(slug));

/** The generated full-screen page of a document page slug, from the docs root. */
export const standaloneDocFile = (slug: string): string => pageRel(standaloneDocId(slug));

/** The generated standalone page of a deck page slug, from the docs root. */
export const standaloneDeckFile = (slug: string): string => pageRel(standaloneDeckId(slug));

export const DOCS_SSG_AUTHORING = ['pages', 'lib', 'runtime', 'public', 'data', 'config.ts', 'tsconfig.json', 'dist'];

/** True for src/documentation-relative paths that are SSG authoring inputs. */
export function isDocsSsgAuthoring(relFromSrcDocumentation: string): boolean {
  const r = relFromSrcDocumentation.replace(/\\/g, '/');
  return DOCS_SSG_AUTHORING.some((d) => r === d || r.startsWith(d + '/'));
}

/** True for src/-relative paths (e.g. "documentation/pages/badge.mdx"). */
export function isDocsSsgAuthoringSrc(relFromSrc: string): boolean {
  const r = relFromSrc.replace(/\\/g, '/');
  return r.startsWith('documentation/') && isDocsSsgAuthoring(r.slice('documentation/'.length));
}

/** Where a dist/documentation/{rel} artifact originates in src/documentation.
 *  Returns the src/-relative counterpart, or null for generated files. */
export function docsDistToSrc(relFromDistDocumentation: string): string | null {
  const r = relFromDistDocumentation.replace(/\\/g, '/');
  // generated by the search-index post plugin
  if (r === 'js/search-index.js') return null;
  // compiled runtime: dist/documentation/js/{n}.js ← runtime/{n}.ts
  const js = r.match(/^js\/(.+)\.js$/);
  if (js) return `documentation/runtime/${js[1]}.ts`;
  // static assets live in public/ (mirrored to output root by defuss-ssg)
  if (/^(css|fonts|images|videos|templates)\//.test(r)) return `documentation/public/${r}`;
  // a standalone page (<section>/deck-{n}.html, app-{n}.html, full-{n}.html) ← its source page's
  // example fence; every other page: <section>/{n}.html ← pages/<section>/{n}.mdx
  if (r.endsWith('.html')) {
    const id = r.replace(/^.*\//, '').replace(/\.html$/, '');
    return `documentation/pages/${pageSourceRel(standaloneSource(id) ?? id)}`;
  }
  return null;
}

/** The ```html example fence a standalone deck / full-screen scaffold or document page is generated from: the one
 *  flagged `standalone` (````html example standalone label=...`), else the first that is no part fence - a page
 *  leads with its individual examples (AGENTS.md "Individual examples"), so its first fence may be a part, or a
 *  moved individual example (the Invoice page's "Exact amounts" came before its 30-line invoice). Null when the page
 *  has none. A fence may open with more than three backticks when its body holds a ``` line (CommonMark;
 *  scripts/lib/format-pages.ts grows it); its closing fence is the same length. VERIFIED: (tests/format-pages.test.ts)
 *  a grown fence reads through here as its body. */
export function exampleFence(mdx: string): string | null {
  const fences = [...mdx.matchAll(/^(`{3,})(html example[^\n]*)\n([\s\S]*?)^\1$/gm)].map((m) => ({ flags: fenceFlags(m[2]), body: m[3] }));
  return (fences.find((f) => f.flags.includes('standalone')) ?? fences.find((f) => !f.flags.includes('part')))?.body ?? null;
}

